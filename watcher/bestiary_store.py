"""Read-only Bestiary data access. No Tk or global application state.

The database is generated by tools/build_bestiary_index.py from source-backed
JSON. Public API: search(), detail(), areas(), races(), ranks(), close().
"""

from __future__ import annotations

import json
import re
import sqlite3
import zlib
from pathlib import Path
from watcher.bestiary_labels import FACTIONS


LINK_ID = re.compile(r"(?:pulse://npc/|https?://kb\.aionempire\.com/npc/)(\d+)", re.IGNORECASE)


# Preset zlib dictionary for the per-NPC detail blobs: their keys and boilerplate repeat in every row.
DETAIL_DICT = (
    '{"id":"","name":"","internal_name":"","category":"monster","role":"","title":"","description":"",'
    '"stock":"","trade_tabs":[],"stock_source":"client_npcs.xml + client_npc_goodslist.xml + '
    'client_npc_trade_in_list.xml + client_items.xml","race":"","faction":"","kind":"","rank":"","level":"",'
    '"hp_bar":null,"icon_asset":"","stats":{"Макс. ХП":"","Опыт":""},"drops":"","points":[{"mob_id":"",'
    '"x":,"y":,"gx":,"gy":,"gz":,"source":"level","map_id":"2100"}],"kb_locations":[{"slug":"","name":"",'
    '"count":}],"kb_url":"https://kb.aionempire.com/npc/","kb_status":"","seller_inventory_state":"",'
    '"Монстр","Торговец","NPC","Элийцы","Асмодиане","Балауры","Другие","Обычный","Элитный","Герой","Легенда"'
).encode("utf-8")


def unpack_detail(blob: bytes) -> dict:
    unpacker = zlib.decompressobj(zdict=DETAIL_DICT)
    return json.loads(unpacker.decompress(blob) + unpacker.flush())


def search_key(value: str) -> str:
    """Case-insensitive text matching and in-app NPC links."""
    value = value.strip()
    link = LINK_ID.search(value)
    return link.group(1) if link else value.casefold()


class BestiaryStore:
    def __init__(self, path: Path):
        self.path = Path(path)
        self.connection = sqlite3.connect(f"file:{self.path.as_posix()}?mode=ro", uri=True)
        self.connection.row_factory = sqlite3.Row
        version = self.connection.execute("PRAGMA user_version").fetchone()[0]
        self.version = version
        if version not in (1, 2, 3, 4, 5):
            self.close()
            raise ValueError(f"Неизвестный формат базы бестиария: {version}")

    def close(self) -> None:
        self.connection.close()

    def coverage(self) -> tuple[int, int, int]:
        row = self.connection.execute("SELECT count(*),sum(has_profile),sum(level != '') FROM npc").fetchone()
        return tuple(int(value or 0) for value in row)

    def races(self) -> list[str]:
        if self.version >= 2:
            return list(FACTIONS)
        return [
            row[0] for row in self.connection.execute(
                "SELECT race FROM npc WHERE race != '' GROUP BY race ORDER BY count(*) DESC, race"
            )
        ]

    def ranks(self) -> list[str]:
        return [
            row[0] for row in self.connection.execute(
                "SELECT rank FROM npc WHERE rank != '' GROUP BY rank ORDER BY count(*) DESC, rank"
            )
        ]

    def zones(self) -> list[tuple[str, str]]:
        return [
            (row[0], row[1]) for row in self.connection.execute(
                "SELECT map_id,name FROM npc_zone GROUP BY map_id ORDER BY name,map_id"
            )
        ]

    def search(
        self, text: str = "", category: str = "", race: str = "", rank: str = "",
        map_id: str = "", offset: int = 0, limit: int = 150,
        min_level: int | None = None, max_level: int | None = None, region: str = "",
    ) -> tuple[list[dict], int]:
        clauses: list[str] = []
        params: list[object] = []
        term = search_key(text)
        if term:
            # The index also covers internal and localized names and the numeric ID.
            clauses.append("n.search_text LIKE ? ESCAPE '\\'")
            escaped = term.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
            params.append(f"%{escaped}%")
        if self.version >= 5:  # technical and duplicate records are a group of their own
            clauses.append("n.service = ?")
            params.append(1 if category == "service" else 0)
        if category == "monster":
            clauses.append("n.category = 'monster'")
        elif category == "npc":
            clauses.append("n.category = 'npc'")
        elif category == "merchant":
            clauses.append("(n.role = 'merchant' OR n.kind = 'Торговец')")
        if race:
            clauses.append("n.faction = ?" if self.version >= 2 and race in FACTIONS else "n.race = ?")
            params.append(race)
        if rank:
            clauses.append("n.rank = ?")
            params.append(rank)
        if map_id:
            clauses.append("EXISTS (SELECT 1 FROM npc_zone z WHERE z.npc_id=n.id AND z.map_id=?)")
            params.append(map_id)
        if min_level is not None or max_level is not None:
            clauses.append("n.level != ''")
        if min_level is not None:
            clauses.append("CAST(n.level AS INTEGER) >= ?")
            params.append(min_level)
        if max_level is not None:
            clauses.append("CAST(n.level AS INTEGER) <= ?")
            params.append(max_level)
        if region and self.version >= 3:
            clauses.append("EXISTS (SELECT 1 FROM npc_region r WHERE r.npc_id=n.id AND r.name=?" + (" AND r.map_id=?" if map_id else "") + ")")
            params.append(region)
            if map_id:
                params.append(map_id)
        where = " WHERE " + " AND ".join(clauses) if clauses else ""
        total = self.connection.execute("SELECT count(*) FROM npc n" + where, params).fetchone()[0]
        rows = self.connection.execute(
            "SELECT n.id,n.name,n.kind,n.race,n.rank,n.level,n.icon_asset,n.zone_names,"
            + ("n.faction," if self.version >= 2 else "'' AS faction,")
            + "n.point_count,n.drop_count,n.has_profile FROM npc n" + where
            + " ORDER BY n.has_profile DESC,n.point_count DESC,n.name COLLATE NOCASE,n.id LIMIT ? OFFSET ?",
            [*params, limit, offset],
        ).fetchall()
        return [dict(row) for row in rows], total

    def regions(self, map_id: str = "") -> list[str]:
        if self.version < 3:
            return []
        return [row[0] for row in self.connection.execute(
            "SELECT DISTINCT name FROM npc_region" + (" WHERE map_id=?" if map_id else "") + " ORDER BY name",
            (map_id,) if map_id else ())]

    def detail(self, npc_id: str) -> dict | None:
        row = self.connection.execute("SELECT detail FROM npc WHERE id=?", (str(npc_id),)).fetchone()
        if not row:
            return None
        detail = unpack_detail(row[0])
        if self.version >= 4:  # drops are item ids; the item table holds name, rarity and icon once
            detail["drops"] = self._items(self._shared(detail.get("drops")))
            detail["stock"] = self._shared(detail.get("stock"))
        return detail

    def _shared(self, key: str | list | None) -> list:
        if not key:
            return []
        if not isinstance(key, str):
            return key
        row = self.connection.execute("SELECT data FROM shared WHERE key=?", (key,)).fetchone()
        return json.loads(zlib.decompress(row[0])) if row else []

    def _items(self, ids: list[str]) -> list[dict]:
        found: dict[str, dict] = {}
        for start in range(0, len(ids), 500):
            chunk = ids[start:start + 500]
            marks = ",".join("?" * len(chunk))
            for row in self.connection.execute(
                f"SELECT item_id,name,rarity,icon FROM item WHERE item_id IN ({marks})", chunk
            ):
                found[row[0]] = {"item_id": row[0], "name": row[1], "rarity": row[2], "icon": row[3]}
        return [found.get(item_id, {"item_id": item_id}) for item_id in ids]

    def areas(self, npc_id: str) -> list[dict]:
        rows = self.connection.execute(
            "SELECT map_id,area_id,point_count,center_x,center_y,names,polygon FROM npc_area "
            "WHERE npc_id=? ORDER BY point_count DESC", (str(npc_id),)
        ).fetchall()
        return [
            {
                "map_id": row["map_id"], "area_id": row["area_id"], "point_count": row["point_count"],
                "center": (row["center_x"], row["center_y"]), "names": json.loads(row["names"]),
                "polygon": json.loads(row["polygon"]),
            }
            for row in rows
        ]
